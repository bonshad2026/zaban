  const ATTRIBUTES = ["placeholder", "title", "aria-label"];
  const originals = new WeakMap();
  let english = false;

  // Returns the English text for a Persian text, or null when the text is not a known label.
  function translate(text) {
    const key = text.trim();
    if (!key || !Object.prototype.hasOwnProperty.call(EN, key)) return null;
    return text.replace(key, EN[key]);
  }

  function translateTextNode(node) {
    const current = node.nodeValue;
    const memory = originals.get(node);
    // A changed value that is not what this script wrote is a new Persian text.
    const original = memory && current === memory.out ? memory.original : current;
    const out = english ? translate(original) ?? original : original;
    originals.set(node, { original, out: out === current ? undefined : out });
    if (out !== current) node.nodeValue = out;
  }

  function translateElement(element) {
    ATTRIBUTES.forEach((name) => {
      if (!element.hasAttribute(name)) return;
      const current = element.getAttribute(name);
      const memory = originals.get(element) || {};
      const original = memory[name] && current === memory[name].out ? memory[name].original : current;
      const out = english ? translate(original) ?? original : original;
      memory[name] = { original, out: out === current ? undefined : out };
      originals.set(element, memory);
      if (out !== current) element.setAttribute(name, out);
    });
  }

  function translateTree(root) {
    if (root.nodeType === Node.TEXT_NODE) {
      translateTextNode(root);
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE) return;
    if (["SCRIPT", "STYLE"].includes(root.tagName)) return;
    translateElement(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
      else translateElement(node);
      node = walker.nextNode();
    }
  }

